-- C09/C10 Echo search-only schema. Apply explicitly after review; NEVER at request time.
-- Does not edit R2 source, subtitles, member rights, QA quotas, model routing, or batteries.
CREATE TABLE IF NOT EXISTS qa_search_state (
  trackId TEXT PRIMARY KEY,
  activeGeneration TEXT NOT NULL,
  sourceKey TEXT NOT NULL,
  sourceUpdatedAt INTEGER NOT NULL,
  segmentCount INTEGER NOT NULL DEFAULT 0,
  updatedAt INTEGER NOT NULL,
  invalidated INTEGER NOT NULL DEFAULT 0,
  changeRevision INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS qa_search_segments (
  id INTEGER PRIMARY KEY,
  trackId TEXT NOT NULL,
  generation TEXT NOT NULL,
  segmentId TEXT NOT NULL,
  fromSegment TEXT NOT NULL,
  toSegment TEXT NOT NULL,
  startMs INTEGER NOT NULL,
  endMs INTEGER NOT NULL,
  speaker TEXT NOT NULL,
  content TEXT NOT NULL,
  searchTokens TEXT NOT NULL,
  UNIQUE(trackId,generation,segmentId)
);
CREATE INDEX IF NOT EXISTS qa_search_segments_generation ON qa_search_segments(trackId,generation);
-- Unicode61 indexes separate Chinese two-character terms generated by the application,
-- avoiding trigram's inability to search exactly two Han characters.
CREATE VIRTUAL TABLE IF NOT EXISTS qa_search_fts USING fts5(
  searchTokens,content='qa_search_segments',content_rowid='id',tokenize='unicode61'
);
CREATE TRIGGER IF NOT EXISTS qa_search_segments_ai AFTER INSERT ON qa_search_segments BEGIN
  INSERT INTO qa_search_fts(rowid,searchTokens) VALUES(new.id,new.searchTokens);
END;
CREATE TRIGGER IF NOT EXISTS qa_search_segments_ad AFTER DELETE ON qa_search_segments BEGIN
  INSERT INTO qa_search_fts(qa_search_fts,rowid,searchTokens) VALUES('delete',old.id,old.searchTokens);
END;
-- Do not use REPLACE/update for segment rows; build a new generation then flip the state.

-- Durable per-track index-rebuild intent. Corrections and rights updates
-- are committed atomically with this work item; no unbounded cron scanning.
CREATE TABLE IF NOT EXISTS qa_search_rebuild_jobs (
  trackId TEXT PRIMARY KEY,
  requestedRevision INTEGER NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',
  attempts INTEGER NOT NULL DEFAULT 0,
  nextAttemptAt INTEGER NOT NULL DEFAULT 0,
  leaseUntil INTEGER NOT NULL DEFAULT 0,
  updatedAt INTEGER NOT NULL DEFAULT 0,
  lastError TEXT
);
CREATE INDEX IF NOT EXISTS qa_search_rebuild_ready
  ON qa_search_rebuild_jobs(status,nextAttemptAt,updatedAt);

-- These tables must already exist from Echo's existing transcript schema.
-- All triggers run in the SAME D1 transaction as the source mutation.
-- Corrections never update original R2, they only invalidate derived search.
CREATE TRIGGER IF NOT EXISTS qa_search_moderation_insert AFTER INSERT ON transcript_correction_events BEGIN
  INSERT INTO qa_search_state(trackId,activeGeneration,sourceKey,sourceUpdatedAt,segmentCount,updatedAt,invalidated,changeRevision)
    VALUES(NEW.trackId,'','',0,0,0,1,1)
    ON CONFLICT(trackId) DO UPDATE SET invalidated=1,changeRevision=changeRevision+1;
  INSERT INTO qa_search_rebuild_jobs(trackId,requestedRevision,status,attempts,nextAttemptAt,leaseUntil,updatedAt,lastError)
    SELECT NEW.trackId,s.changeRevision,'pending',0,0,0,0,NULL FROM qa_search_state s WHERE s.trackId=NEW.trackId
    ON CONFLICT(trackId) DO UPDATE SET requestedRevision=excluded.requestedRevision,status='pending',
      attempts=0,nextAttemptAt=0,leaseUntil=0,updatedAt=0,lastError=NULL;
END;
